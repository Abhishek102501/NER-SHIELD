/** Bounding box across all seven states, in [lng, lat]. */
export const NE_BOUNDS = {
  minLng: 89.6986,
  maxLng: 97.4115,
  minLat: 21.9776,
  maxLat: 29.46,
};

/**
 * Builds a [lng, lat] → [x, y] projector that fits `NE_BOUNDS` into a `width`×`height`
 * box, preserving aspect ratio via a latitude-corrected equirectangular projection
 * (adequate at this regional scale — no need for a full map-projection library).
 */
export function makeNeProjector(width: number, height: number, padding = 0) {
  const cosLat = Math.cos(((NE_BOUNDS.minLat + NE_BOUNDS.maxLat) / 2) * (Math.PI / 180));
  const spanX = (NE_BOUNDS.maxLng - NE_BOUNDS.minLng) * cosLat;
  const spanY = NE_BOUNDS.maxLat - NE_BOUNDS.minLat;
  const scale = Math.min((width - 2 * padding) / spanX, (height - 2 * padding) / spanY);
  const offsetX = (width - spanX * scale) / 2;
  const offsetY = (height - spanY * scale) / 2;

  return function project([lng, lat]: [number, number]): [number, number] {
    const x = offsetX + (lng - NE_BOUNDS.minLng) * cosLat * scale;
    const y = height - offsetY - (lat - NE_BOUNDS.minLat) * scale;
    return [x, y];
  };
}
